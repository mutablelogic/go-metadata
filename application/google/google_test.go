package google_test

import (
	"context"
	"io"
	"maps"
	"strings"
	"testing"

	// Packages
	metadata "github.com/mutablelogic/go-metadata"
	_ "github.com/mutablelogic/go-metadata/application/google"
)

// named is a reader with a name
type named struct {
	io.Reader
	name string
}

func (r named) Name() string { return r.name }

// googleMeta returns the metadata of the Google document, by key, with its
// content type detected from its name and contents
func googleMeta(t *testing.T, name, content string) map[string]string {
	t.Helper()
	_, meta, err := metadata.Extract(context.Background(), named{strings.NewReader(content), name})
	if err != nil {
		t.Fatal(err)
	}
	result := make(map[string]string, len(meta))
	for _, m := range meta {
		result[m.NS()+string(metadata.Separator)+m.Key()] = m.Value()
	}
	return result
}

func Test_google_000(t *testing.T) {
	// The type, identifier, email and URL, as Google Drive for desktop writes
	// them, with the title from the name
	got := googleMeta(t, "/downloads/Bader Pass.gdoc", `{"":"WARNING! DO NOT EDIT THIS FILE! ANY CHANGES MADE WILL BE LOST!","doc_id":"1CMNNX_fNA7RpbeMWPnaUkx2sTZAqqNhsGKvCsJNBn3c","resource_key":"","email":"jane@example.com"}`)
	want := map[string]string{
		"dc:title":      "Bader Pass",
		"dc:identifier": "https://docs.google.com/document/d/1CMNNX_fNA7RpbeMWPnaUkx2sTZAqqNhsGKvCsJNBn3c",
		"google:type":   "document",
		"google:id":     "1CMNNX_fNA7RpbeMWPnaUkx2sTZAqqNhsGKvCsJNBn3c",
		"google:email":  "jane@example.com",
		"dc:type":       "Text",
		"metadata:kind": "document",
	}
	if !maps.Equal(got, want) {
		t.Errorf("expected %v, got %v", want, got)
	}
}

func Test_google_001(t *testing.T) {
	// The resource key is in the URL, which is added to a URL which has a
	// query, and a URL in the file is used
	for _, test := range []struct {
		name, content string
		want          map[string]string
	}{
		{"Ski 2026.gsheet", `{"doc_id":"abc","resource_key":"0-xyz"}`, map[string]string{
			"dc:identifier":       "https://docs.google.com/spreadsheets/d/abc?resourcekey=0-xyz",
			"google:type":         "spreadsheet",
			"google:resource_key": "0-xyz",
		}},
		{"Places.gmap", `{"doc_id":"abc","resource_key":"0-xyz"}`, map[string]string{
			"dc:identifier": "https://www.google.com/maps/d/viewer?mid=abc&resourcekey=0-xyz",
		}},
		{"Untitled drawing.GDRAW", `{"url":"https://docs.google.com/open?id=abc","doc_id":"abc"}`, map[string]string{
			"dc:identifier": "https://docs.google.com/open?id=abc",
			"google:type":   "drawing",
		}},
	} {
		got := googleMeta(t, test.name, test.content)
		for key, want := range test.want {
			if got[key] != want {
				t.Errorf("%s: %s: expected %q, got %q", test.name, key, want, got[key])
			}
		}
	}
}

func Test_google_002(t *testing.T) {
	// A file which isn't JSON has the title from its name
	if got, want := googleMeta(t, "Notes.gdoc", "not json"), map[string]string{"dc:title": "Notes", "dc:type": "Text", "metadata:kind": "document"}; !maps.Equal(got, want) {
		t.Errorf("expected %v, got %v", want, got)
	}
}

func Test_google_003(t *testing.T) {
	// The files are detected as plain text, and refined by their extension
	contentType, params, err := metadata.ContentType(named{strings.NewReader(`{"doc_id":"abc"}`), "Ski 2026.gsheet"})
	if err != nil {
		t.Fatal(err)
	} else if contentType != "application/vnd.google-apps.spreadsheet" || params["charset"] != "utf-8" {
		t.Errorf("expected application/vnd.google-apps.spreadsheet; charset=utf-8, got %q %v", contentType, params)
	}
}
